import { cascadeThemes, resolveTheme } from "./css-tokens.ts";

/** Stylesheets in the order the web app loads them. */
export const TOKEN_SOURCES = [
  "packages/desktop-ui/src/styles/globals.css",
  "apps/desktop/src/globals.css",
  "apps/web/src/styles.css",
] as const;

export function renderGeneratedTokens(read: (path: string) => string): string {
  const { light, dark } = cascadeThemes(TOKEN_SOURCES.map(read));
  const themes = { light: resolveTheme(light), dark: resolveTheme(dark) };
  return `// Generated by \`pnpm --filter @berry/design-tokens generate\` from:\n${TOKEN_SOURCES.map((path) => `//   ${path}`).join("\n")}\n// Do not edit by hand; change the stylesheets and regenerate.\n\nexport const generatedThemes = ${JSON.stringify(themes, null, 2)} as const;\n`;
}
